// Operators
// Arithmetic Operators:     +, - , * , / , % , **
// Assignment Operators:    = , += , -= , *= , /=
// Comparison Operators:   == , <= , >= , === , > , < , != , !==
// Logical Operators:    && , || ,  ! 
// Unary Operators:       typeof, delete, ++, --
// Modern & Special Operators:       ?:  ,   ?.    ,  in   ,  instanceof  




// Arithmetic Operators
let a=10;
let b=20;
console.log(a+b); //addition
console.log(a-b);//subtraction
console.log(a*b);//multiplication
console.log(a/b);//divide
console.log(a%b);//reminder
console.log(a**b);//power




//Assignment Operators
let c;
console.log(c=2);
console.log(c+=1);
console.log(c-=1);
console.log(c*=1);
console.log(c/=1);




//Comparison Operators
let d=5;
let e=10;
console.log(d==e);//equal  only check value not type
console.log(d!=e);//not equal to
console.log(d===e);//Strictly equal to    check both value and type 
console.log(d!==e);//not Strictly equal to 
console.log(d<=e);//smaller then equal to
console.log(d>=e);//greatert then equal to
console.log(d<e);//smaller
console.log(d>e);//greater




// Logical Operators
console.log(true && false);
console.log(true || false);
console.log(!true);




//Unary Operators
let f=50;
console.log(f++);
console.log(f--);
console.log(typeof(f));
console.log(delete(f));




//grouping
console.log(3+4*4)
